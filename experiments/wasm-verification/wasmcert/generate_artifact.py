#!/usr/bin/env python3
"""Bind Rocq inputs to the existing packaged components, without rewriting Wasm.

Extraction/selection and Python's byte embedding are trusted. Rocq additionally
checks the byte slice and decodes its locals and instructions with WasmCert.
"""
import hashlib
import io
import json
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "out" / "wasmcert"
ENTRY = "petal/split-even/split/[total].json.wasm"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def generate():
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["(* Generated by generate_artifact.py; do not edit. *)",
             "From Stdlib Require Import List Strings.Byte NArith.",
             "Import ListNotations."]
    identities = {}
    for variant in ("correct", "faulty"):
        directory = ROOT / "out" / variant
        report = json.loads((directory / "extract/extraction.json").read_text())
        archive = (directory / "split-even.petal.tar.gz").read_bytes()
        component = (directory / "extract/component.wasm").read_bytes()
        module = (directory / "extract/target-module.wasm").read_bytes()
        require(sha(archive) == report["archive"]["sha256"], "archive hash mismatch")
        require(sha(component) == report["component"]["sha256"], "component hash mismatch")
        require(sha(module) == report["target_module"]["sha256"], "module hash mismatch")
        require(report["component"]["entry"] == ENTRY, "wrong component entry")
        with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as package:
            entries = [entry for entry in package if entry.name == ENTRY]
            require(len(entries) == 1, "component entry missing or duplicated")
            require(package.extractfile(entries[0]).read() == component,
                    "component bytes differ from packaged entry")
        target = report["target_function"]
        require(target["export"] == "bloom_verify_split_even", "wrong export")
        require(target["function_index"] == 67, "wrong function index")
        require(target["defined_function_index"] == 66, "wrong defined-function index")
        require(target["params"] == ["i32", "i64"] and target["results"] == [],
                "unexpected function signature")
        start = target["body_offset_in_module"]
        body = module[start:start + target["body_bytes"]]
        require(sha(body) == target["body_sha256"], "body hash mismatch")
        require(body.hex() == target["body_hex"], "body byte mismatch")
        chunks = []
        for i in range(0, len(module), 256):
            name = f"{variant}_chunk_{i // 256}"
            values = "; ".join(f"Byte.x{b:02x}" for b in module[i:i + 256])
            lines.append(f"Definition {name} : list Byte.byte := [{values}].")
            chunks.append(name)
        lines.append(f"Definition {variant}_bytes : list Byte.byte :=\n"
                     f"  List.concat [{'; '.join(chunks)}].")
        lines.append(f"Definition {variant}_body_offset : nat := {start}.")
        lines.append(f"Definition {variant}_body_length : nat := {len(body)}.")
        lines.append(f"Definition {variant}_type_index : N := {target['type_index']}%N.")
        identities[variant] = {
            "archive_sha256": sha(archive),
            "component_sha256": sha(component),
            "module_sha256": sha(module),
            "module_bytes": len(module),
            "body_sha256": sha(body),
            "function_index": 67,
            "defined_function_index": 66,
            "export": target["export"],
        }
    artifact = "\n".join(lines) + "\n"
    (OUT / "ArtifactBytes.v").write_text(artifact)
    identities["embedding_sha256"] = sha(artifact.encode())
    (OUT / "identities.json").write_text(json.dumps(identities, indent=2) + "\n")


if __name__ == "__main__":
    generate()
