"""Generate KWasm reachability claims about the shipped split-even body.

Runs inside the pinned K container with pykwasm installed. The function body
is decoded by pykwasm's own binary decoder from the bytes recorded in
extraction.json, after checking those bytes are exactly the bytes at the
recorded offset of the extracted module. Nothing here re-implements the
function: the claim's <fCode> is pykwasm's decoding of the shipped body.

usage: python gen_claims.py <extraction.json> <target-module.wasm> <kompiled-dir> <out-prefix>

Writes <out-prefix>-<claim>-spec.k for each claim in CLAIMS, one claim per
file so each gets its own verdict.
"""

from __future__ import annotations

import hashlib
import io
import json
import sys
from pathlib import Path

from pyk.kast.inner import KApply
from pyk.ktool.kprint import KPrint
from pykwasm import kwasm_ast as wast
from pykwasm.binary.combinators import list_of
from pykwasm.binary.instructions import expr
from pykwasm.binary.integers import u32
from pykwasm.binary.types import valtype


def main() -> None:
    extraction_path, module_path, kompiled, out = sys.argv[1:5]
    report = json.loads(Path(extraction_path).read_text())
    target = report['target_function']
    module = Path(module_path).read_bytes()
    if hashlib.sha256(module).hexdigest() != report['target_module']['sha256']:
        raise SystemExit('module hash differs from extraction.json')
    body = bytes.fromhex(target['body_hex'])
    start = target['body_offset_in_module']
    if module[start : start + len(body)] != body:
        raise SystemExit('body bytes are not at the recorded offset')
    if hashlib.sha256(body).hexdigest() != target['body_sha256']:
        raise SystemExit('body hash differs from extraction.json')
    if target['params'] != ['i32', 'i64'] or target['results'] != []:
        raise SystemExit(f'unexpected signature {target["params"]} -> {target["results"]}')

    stream = io.BytesIO(body)

    def local_group(s):
        return u32(s), valtype(s)

    groups = list_of(local_group, stream)
    instrs = expr(stream)
    if stream.read():
        raise SystemExit('trailing bytes after body')
    locals_ = [t for n, t in groups for _ in range(n)]

    printer = KPrint(Path(kompiled))
    # pyk prints #instrWithPos with named arguments, which the claim parser
    # does not accept; print that wrapper positionally, everything else by pyk.
    parts = []
    for item in instrs:
        if not (isinstance(item, KApply) and item.label.name == 'aInstrWithPos'):
            raise SystemExit(f'unexpected decoder output {item}')
        inner, offset, length = item.args
        parts.append(f'#instrWithPos({printer.pretty_print(inner)}, {offset.token}, {length.token})')
    code = '\n'.join(parts + ['.EmptyStmts'])
    local_types = printer.pretty_print(wast.vec_type(wast.val_types(locals_)))
    for claim, (comment, mdata, extra_requires, ensures, lemmas) in CLAIMS.items():
        path = Path(f'{out}-{claim}-spec.k')
        path.write_text(
            TEMPLATE.format(
                body_sha256=target['body_sha256'],
                module_sha256=report['target_module']['sha256'],
                component_sha256=report['component']['sha256'],
                archive_sha256=report['archive']['sha256'],
                index=target['function_index'],
                code=indent(code, 20),
                local_types=local_types,
                module_name=path.name.removesuffix('.k').upper(),
                claim=claim,
                comment=comment,
                mdata=mdata,
                extra_requires=extra_requires,
                ensures=ensures,
                requires='split-even-lemmas.md' if lemmas else 'kwasm-lemmas.md',
                imports='SPLIT-EVEN-LEMMAS' if lemmas else 'KWASM-LEMMAS',
            )
        )
    print(json.dumps({'decoded_instrs': code, 'decoded_locals': local_types}, indent=1))


def indent(text: str, n: int) -> str:
    return ('\n' + ' ' * n).join(text.splitlines())


# The configuration is the part of KWasm's state the invocation reads. FADDR,
# CUR, MEMADDR, SIZE, BM, VS, LOCALS, TOTAL, P and Q are universally
# quantified. These are reachability/partial-correctness claims. Do not infer
# termination for arbitrary code from a successful reachability check. For this
# particular body, the separate decoded-instruction review establishes a finite,
# call-free sequence: under PRE both stores are in bounds, and none of the other
# instructions traps. The return-state claim is meaningful together with that
# argument, not a general total-correctness mode of K.
TEMPLATE = """\
// GENERATED by kwasm/gen_claims.py. Do not edit.
// archive   sha256 {archive_sha256}
// component sha256 {component_sha256}
// module    sha256 {module_sha256}
// function  index {index}, body sha256 {body_sha256}
// <fCode> is pykwasm's decoding of exactly those body bytes.

requires "{requires}"

module {module_name}
    imports {imports}

    // {comment}
    claim [{claim}]:
          <instrs> ( invoke FADDR ) => .K ... </instrs>
          <valstack> < i64 > TOTAL : < i32 > P : VS => VS </valstack>
          <locals> LOCALS </locals>
          <curModIdx> CUR </curModIdx>
          <moduleInst>
            <modIdx> CUR </modIdx>
            <memAddrs> 0 |-> MEMADDR </memAddrs>
            ...
          </moduleInst>
          <funcDef>
            <fAddr> FADDR </fAddr>
            <fCode> {code} </fCode>
            <fType> [ i32 i64 .ValTypes ] -> [ .ValTypes ] </fType>
            <fLocal> {local_types} </fLocal>
            <fModInst> CUR </fModInst>
            ...
          </funcDef>
          <memInst>
            <mAddr> MEMADDR </mAddr>
            <msize> SIZE </msize>
            <mdata> {mdata} </mdata>
            ...
          </memInst>
        requires #inUnsignedRange(i32, P)
         andBool #inUnsignedRange(i64, TOTAL)
         andBool P +Int 16 <=Int SIZE *Int #pageSize(){extra_requires}{ensures}
endmodule
"""

FIRST = '#getRange(?BM2, P, 8)'
SECOND = '#getRange(?BM2, P +Int 8, 8)'

CLAIMS = {
    'returns': (
        'Normal return target state; combine with the reviewed finite-body argument',
        'BM => ?BM2',
        '',
        '',
        False,
    ),
    # name: (comment, mdata, extra requires, ensures, uses split-even-lemmas.md)
    # P-RET, P-SUM, P-ORD, P-GAP over mathematical integers, on the bytes read
    # back from memory, whatever term KWasm builds for the final memory.
    'props': (
        'P-RET + P-SUM + P-ORD + P-GAP (KWasm lemmas only)',
        'BM => ?BM2',
        '',
        f"""
        ensures {FIRST} +Int {SECOND} ==Int TOTAL
         andBool {FIRST} <=Int {SECOND}
         andBool {SECOND} -Int {FIRST} <=Int 1""",
        False,
    ),
    'props-lemma': (
        'P-RET + P-SUM + P-ORD + P-GAP (with the trusted shift lemma)',
        'BM => ?BM2',
        '',
        f"""
        ensures {FIRST} +Int {SECOND} ==Int TOTAL
         andBool {FIRST} <=Int {SECOND}
         andBool {SECOND} -Int {FIRST} <=Int 1""",
        True,
    ),
    # P-RET + P-FRAME, split at the slot because the backend does not case
    # split a disjunctive precondition.
    'frame-below': (
        'P-RET + P-FRAME for bytes below the slot',
        'BM => ?BM2',
        """
         andBool 0 <=Int Q andBool Q +Int 1 <=Int P""",
        """
        ensures #getRange(?BM2, Q, 1) ==Int #getRange(BM, Q, 1)""",
        False,
    ),
    'frame-above': (
        'P-RET + P-FRAME for bytes above the slot',
        'BM => ?BM2',
        """
         andBool P +Int 16 <=Int Q andBool Q <Int SIZE *Int #pageSize()""",
        """
        ensures #getRange(?BM2, Q, 1) ==Int #getRange(BM, Q, 1)""",
        False,
    ),
    # P-RET + exact final memory, written with division rather than the
    # shift the code uses, so it does not restate the implementation.
    'exact-lemma': (
        'P-RET + exact final memory: first = TOTAL div 2, second = TOTAL - first',
        'BM => #setRange(#setRange(BM, P, TOTAL /Int 2, 8), P +Int 8, TOTAL -Int (TOTAL /Int 2), 8)',
        '',
        '',
        True,
    ),
}


if __name__ == '__main__':
    main()
