#!/usr/bin/env python3
"""Embed the two loops-io proof targets as Rocq byte lists.

Experiment 1 (byte-sum): like ../../wasmcert/generate_artifact.py, the trusted
extractor selects the core module and function body from the packaged Petal;
Rocq slices and decodes the body.

Experiment 2 (upper WASI): the whole 517-byte module is embedded and Rocq
decodes the whole module, so no extractor or selection step is trusted.
"""
import hashlib
import io
import json
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "out" / "rocq"
ENTRY = "petal/byte-sum/sum/[text].json.wasm"
WASI = ROOT / "wasi-petal/target/wasm32-wasip1/release/upper-wasi-petal.wasm"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def require(ok, message):
    if not ok:
        raise ValueError(message)


def byte_lines(name, data):
    lines, chunks = [], []
    for i in range(0, len(data), 256):
        chunk = f"{name}_chunk_{i // 256}"
        values = "; ".join(f"Byte.x{b:02x}" for b in data[i:i + 256])
        lines.append(f"Definition {chunk} : list Byte.byte := [{values}].")
        chunks.append(chunk)
    lines.append(f"Definition {name} : list Byte.byte :=\n  List.concat [{'; '.join(chunks)}].")
    return lines


HEADER = ["(* Generated by loops-io/rocq/generate.py; do not edit. *)",
          "From Stdlib Require Import List Strings.Byte NArith.",
          "Import ListNotations."]


def byte_sum():
    directory = ROOT / "out" / "byte-sum"
    report = json.loads((directory / "extract/extraction.json").read_text())
    archive = (directory / "byte-sum.petal.tar.gz").read_bytes()
    component = (directory / "extract/component.wasm").read_bytes()
    module = (directory / "extract/target-module.wasm").read_bytes()
    require(sha(archive) == report["archive"]["sha256"], "archive hash mismatch")
    require(sha(component) == report["component"]["sha256"], "component hash mismatch")
    require(sha(module) == report["target_module"]["sha256"], "module hash mismatch")
    require(report["component"]["entry"] == ENTRY, "wrong component entry")
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as package:
        entries = [e for e in package if e.name == ENTRY]
        require(len(entries) == 1, "component entry missing or duplicated")
        require(package.extractfile(entries[0]).read() == component, "component differs")
    target = report["target_function"]
    require(target["export"] == "bloom_verify_byte_sum", "wrong export")
    require(target["params"] == ["i32", "i32"] and target["results"] == ["i64"], "signature")
    start = target["body_offset_in_module"]
    body = module[start:start + target["body_bytes"]]
    require(sha(body) == target["body_sha256"], "body hash mismatch")
    lines = HEADER + byte_lines("byte_sum_module", module) + [
        f"Definition byte_sum_body_offset : nat := {start}.",
        f"Definition byte_sum_body_length : nat := {len(body)}.",
        f"Definition byte_sum_type_index : N := {target['type_index']}%N.",
        f"Definition byte_sum_function_index : N := {target['function_index']}%N."]
    (OUT / "ByteSumBytes.v").write_text("\n".join(lines) + "\n")
    return {"archive_sha256": sha(archive), "component_sha256": sha(component),
            "module_sha256": sha(module), "module_bytes": len(module),
            "body_sha256": sha(body), "body_bytes": len(body),
            "function_index": target["function_index"], "export": target["export"]}


def upper():
    module = WASI.read_bytes()
    lines = HEADER + byte_lines("upper_module", module)
    (OUT / "UpperBytes.v").write_text("\n".join(lines) + "\n")
    return {"module_sha256": sha(module), "module_bytes": len(module), "export": "_start"}


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    ids = {"byte_sum": byte_sum(), "upper": upper()}
    (OUT / "identities.json").write_text(json.dumps(ids, indent=2) + "\n")
    print(json.dumps(ids, indent=2))
